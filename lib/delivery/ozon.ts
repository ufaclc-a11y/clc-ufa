import type { DeliveryProvider, DeliveryQuote, PickupPoint } from './types'

/**
 * Доставка Ozon — ЗАГЛУШКА, интеграция не написана.
 *
 * Почему не написана, хотя договор есть:
 *
 * 1. Ozon Rocket — сервис, под который сделаны все существующие модули для
 *    CMS, — закрыт. Его заменила «Озон доставка» (Ozon Логистика) с другим API.
 *    Писать по документации Rocket означало бы писать под мёртвый сервис.
 * 2. У «Озон доставки» другая схема авторизации: api-key выдаёт персональный
 *    менеджер при заключении договора, по нему получают JWT со сроком жизни
 *    около часа. Публичной спецификации расчёта тарифов нет — она в личном
 *    кабинете продавца.
 *
 * Что нужно, чтобы дописать: подтверждение, что «Озон доставка» подключена к
 * вашему договору, ключи и актуальная документация методов расчёта и списка
 * пунктов выдачи. После этого остаётся заполнить три метода ниже — остальное
 * (роуты, интерфейс оформления, сборка посылки) уже готово и общее с СДЭК.
 *
 * Пока isConfigured() возвращает false, выбор «Ozon» в оформлении работает:
 * покупатель видит, что стоимость сообщит менеджер, и заказ оформляется.
 */

const clientId = () => process.env.OZON_CLIENT_ID?.trim() ?? ''
const apiKey   = () => process.env.OZON_API_KEY?.trim() ?? ''

const NOT_IMPLEMENTED =
  'Интеграция с «Озон доставкой» не подключена: нужны ключи и документация из личного кабинета'

export const ozon: DeliveryProvider = {
  id: 'ozon',

  /*
   * Намеренно false даже при заполненных ключах: ключи сами по себе не делают
   * интеграцию рабочей, а «настроенный» провайдер без реализации выглядел бы
   * как поломка. Снять заглушку — вместе с реализацией методов ниже.
   */
  isConfigured() {
    return false
  },

  /** Заполнены ли ключи — подсказка при подключении. */
  hasCredentials(): boolean {
    return Boolean(clientId() && apiKey())
  },

  // Аргументы не принимаем: методы сразу бросают, а неиспользуемые параметры
  // только шумят в линте. Сигнатуре интерфейса это не противоречит.
  async quotes(): Promise<DeliveryQuote[]> {
    throw new Error(NOT_IMPLEMENTED)
  },

  async points(): Promise<PickupPoint[]> {
    throw new Error(NOT_IMPLEMENTED)
  },
}
