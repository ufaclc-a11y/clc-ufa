// Сканирует public/images/portfolio и пишет data/portfolio.generated.ts —
// список реальных файлов, сгруппированный по префиксу (категории).
// Запускается автоматически в predev/prebuild. Добавление/удаление фото
// в папке отражается на сайте без правок кода.

import { readdirSync, writeFileSync } from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'public', 'images', 'portfolio')

// prefix-NNN.ext → группируем по prefix, сортируем по числу
const re = /^(.+)-(\d+)\.(jpe?g|png|webp)$/i

const groups = {}
for (const file of readdirSync(dir)) {
  const m = file.match(re)
  if (!m) continue
  const prefix = m[1]
  ;(groups[prefix] ??= []).push({ file, n: parseInt(m[2], 10) })
}

const out = {}
for (const prefix of Object.keys(groups).sort()) {
  out[prefix] = groups[prefix].sort((a, b) => a.n - b.n).map(x => x.file)
}

const banner =
  '// AUTO-GENERATED by scripts/gen-portfolio.mjs — НЕ редактировать вручную.\n' +
  '// Обновляется автоматически в predev/prebuild по содержимому public/images/portfolio.\n\n'
const body =
  'export const portfolioFiles: Record<string, string[]> = ' +
  JSON.stringify(out, null, 2) + '\n'

writeFileSync(path.join(root, 'data', 'portfolio.generated.ts'), banner + body)

const total = Object.values(out).reduce((s, a) => s + a.length, 0)
console.log(`portfolio.generated.ts: ${Object.keys(out).length} категорий, ${total} фото`)
