// Генерирует data/portfolio.generated.ts из манифеста data/portfolio-tags.json.
// Манифест ({ "файл.jpg": { categories:[...], order:{cat:n} } }) — источник истины
// связи «фото → категории»; один физический файл может входить в несколько категорий.
// Запускается автоматически в predev/prebuild. См. migrate_portfolio_dedup.py / import_new.py.

import { readFileSync, writeFileSync, existsSync } from 'fs'
import path from 'path'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const manifestPath = path.join(root, 'data', 'portfolio-tags.json')
const portfolioDir = path.join(root, 'public', 'images', 'portfolio')

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))

// Категория → [{ file, order }] ; одно имя может попасть в несколько категорий
const byCat = {}
const missing = []
for (const [file, meta] of Object.entries(manifest)) {
  if (!existsSync(path.join(portfolioDir, file))) missing.push(file)
  for (const cat of meta.categories) {
    const order = meta.order?.[cat] ?? 1e9
    ;(byCat[cat] ??= []).push({ file, order })
  }
}

// Сортируем внутри категории по исходному порядку, затем по имени (детерминированно)
const out = {}
for (const cat of Object.keys(byCat).sort()) {
  out[cat] = byCat[cat]
    .sort((a, b) => a.order - b.order || a.file.localeCompare(b.file))
    .map(x => x.file)
}

const banner =
  '// AUTO-GENERATED by scripts/gen-portfolio.mjs — НЕ редактировать вручную.\n' +
  '// Источник: data/portfolio-tags.json. Обновляется в predev/prebuild.\n\n'
const body =
  'export const portfolioFiles: Record<string, string[]> = ' +
  JSON.stringify(out, null, 2) + '\n'

// Both consumers use the exact same exhaustive mapping; no preview pagination.
// Missing assets must never produce a seemingly valid deployment/index.
if (missing.length) throw new Error(`Missing portfolio assets: ${missing.join(', ')}`)
const sha256 = Object.fromEntries(Object.keys(manifest).sort().map(file => [
  file, createHash('sha256').update(readFileSync(path.join(portfolioDir, file))).digest('hex'),
]))
writeFileSync(path.join(root, 'data', 'portfolio.generated.ts'), banner + body)
writeFileSync(path.join(root, 'public', 'portfolio-index.json'), JSON.stringify({ version: 1, categories: out, sha256 }, null, 2) + '\n')

const files = Object.keys(manifest).length
const refs = Object.values(out).reduce((s, a) => s + a.length, 0)
console.log(`portfolio.generated.ts: ${Object.keys(out).length} категорий, ${files} файлов, ${refs} вхождений`)
if (missing.length) {
  console.warn(`⚠ В манифесте ${missing.length} файлов нет на диске:`, missing.slice(0, 10).join(', ') + (missing.length > 10 ? ' …' : ''))
}
