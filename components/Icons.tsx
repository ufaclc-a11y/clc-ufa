/** Карта символов → компонент иконки для калькулятора / advantage-карточек */
export const ICON_MAP: Record<string, React.FC<IconProps>> = {
  '⚡':  IconBolt,
  '🎨':  IconPalette,
  '⚙️': IconCog,
  '✓':   IconCheck,
  '◎':   IconTarget,
  '✦':   IconStar,
  '↗':   IconArrowUpRight,
  '▣':   IconGrid,
  '◈':   IconDiamond,
  '✉':   IconMessageSquare,
  '🔄':  IconRefresh,
  '📊':  IconBarChart,
  '🏷️': IconTag,
  '🤝':  IconHandshake,
  '📍':  IconMapPin,
}

/** Рендерит SVG-иконку по символу. Фоллбэк — сам символ. */
export function SymbolIcon({
  symbol,
  className,
  size = 20,
}: {
  symbol: string
  className?: string
  size?: number
}) {
  const Comp = ICON_MAP[symbol]
  if (!Comp) return <span className={className} aria-hidden="true">{symbol}</span>
  return <Comp className={className} size={size} />
}
